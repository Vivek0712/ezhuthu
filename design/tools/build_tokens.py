"""Generate tokens.css, app-compat.css, tailwind-preset.js and CONTRAST.md from design/tokens/tokens.json.

Stdlib only. Exits non-zero if any checked text pair fails its WCAG threshold.
Usage: python3 design/tools/build_tokens.py [--check]   (--check: verify generated files are up to date)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOK = ROOT / "tokens"
HEADER = "/* GENERATED by design/tools/build_tokens.py from tokens.json. Do not edit by hand. */\n"


def load() -> dict:
    return json.loads((TOK / "tokens.json").read_text())


def resolve(val: str, data: dict) -> str:
    m = re.fullmatch(r"\{([a-z0-9.\-]+)\}", val)
    if not m:
        return val
    node = data
    for k in m.group(1).split("."):
        node = node[k]
    return node["$value"]


def semantic(data: dict) -> dict[str, dict[str, str]]:
    out = {}
    for name, v in data["semantic"].items():
        if name.startswith("$"):
            continue
        out[name] = {"light": resolve(v["light"], data), "dark": resolve(v["dark"], data)}
    return out


def _lin(c: float) -> float:
    c /= 255
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def luminance(hex_: str) -> float:
    h = hex_.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * _lin(r) + 0.7152 * _lin(g) + 0.0722 * _lin(b)


def ratio(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def contrast_rows(data: dict):
    sem = semantic(data)
    rows = []
    for fg, bg, need in data["contrast"]["pairs"]:
        for mode in ("light", "dark"):
            r = ratio(sem[fg][mode], sem[bg][mode])
            rows.append((mode, fg, bg, sem[fg][mode], sem[bg][mode], r, need, r >= need))
    return rows


def css(data: dict) -> str:
    sem = semantic(data)
    lines = [HEADER, "/* Ezhuthu tokens. Import once at the app root: @import 'design/tokens/tokens.css'; */", ":root {"]
    for fam, shades in data["color"].items():
        for k, v in shades.items():
            if not k.startswith("$"):
                lines.append(f"  --ez-{fam}-{k}: {v['$value']};")
    lines.append("")
    for name, v in sem.items():
        lines.append(f"  --ez-{name}: {v['light']};")
    for k, v in data["space"].items():
        if not k.startswith("$"):
            lines.append(f"  --ez-space-{k}: {v};")
    for k, v in data["radius"].items():
        lines.append(f"  --ez-radius-{k}: {v};")
    for k, v in data["shadow"]["light"].items():
        lines.append(f"  --ez-shadow-{k}: {v};")
    for k, v in data["motion"]["duration"].items():
        lines.append(f"  --ez-dur-{k}: {v};")
    for k, v in data["motion"]["easing"].items():
        lines.append(f"  --ez-ease-{k}: {v};")
    for k, v in data["font"]["family"].items():
        lines.append(f"  --ez-font-{k}: {v};")
    for k, v in data["font"]["scale"].items():
        if k.startswith("$"):
            continue
        lines.append(f"  --ez-text-{k}: {v['size']};")
        lines.append(f"  --ez-lh-{k}: {v['lh-latin']};")
        lines.append(f"  --ez-lh-{k}-ta: {v['lh-ta']};")
    for k, v in data["font"]["weight"].items():
        lines.append(f"  --ez-weight-{k}: {v};")
    lines.append("  color-scheme: light;\n}")

    def dark_block() -> list[str]:
        b = [f"  --ez-{n}: {v['dark']};" for n, v in sem.items()]
        b += [f"  --ez-shadow-{k}: {v};" for k, v in data["shadow"]["dark"].items()]
        b.append("  color-scheme: dark;")
        return b

    lines.append("\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {")
    lines += ["  " + x for x in dark_block()]
    lines.append("  }\n}\n:root[data-theme='dark'] {")
    lines += dark_block()
    lines.append("}\n")
    lines.append(
        "/* Tamil-first line heights: any element in Tamil gets the taller rhythm. */\n"
        ":lang(ta) { line-height: var(--ez-lh-md-ta); }\n"
        "@media (prefers-reduced-motion: reduce) {\n"
        "  :root { --ez-dur-instant: 0ms; --ez-dur-fast: 0ms; --ez-dur-base: 0ms; --ez-dur-slow: 0ms; "
        "--ez-dur-reveal: 0ms; }\n}\n"
    )
    return "\n".join(lines)


APP_COMPAT = {
    "bg": "bg", "surface": "surface", "surface-2": "surface-sunk", "leaf": "leaf", "leaf-edge": "leaf-edge",
    "ink": "text", "ink-2": "text-muted", "line": "border", "accent": "accent", "accent-ink": "on-accent",
    "accent-soft": "accent-soft", "gold": "lamp-text", "ok": "ok", "ok-soft": "ok-soft", "warn": "lamp-text",
    "warn-soft": "lamp-soft", "bad": "error", "bad-soft": "error-soft", "carve-hi": "carve-hi",
    "carve-lo": "carve-lo", "shadow": "shadow-2", "radius": "radius-lg", "font-body": "font-body",
    "font-display": "font-display-latin",
}


def app_compat() -> str:
    lines = [HEADER, "/* Wave-2 bridge for app/web: maps the variable names in app/web/src/styles/app.css",
             "   onto Ezhuthu tokens. Import after tokens.css and delete the app's own :root colour blocks. */",
             ":root, :root[data-theme='dark'] {"]
    for old, new in APP_COMPAT.items():
        lines.append(f"  --{old}: var(--ez-{new});")
    lines.append("  --unsure: var(--ez-unsure);\n  --unsure-soft: var(--ez-unsure-soft);\n}")
    lines.append("@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {")
    for old, new in APP_COMPAT.items():
        lines.append(f"    --{old}: var(--ez-{new});")
    lines.append("  }\n}\n")
    return "\n".join(lines)


def tailwind(data: dict) -> str:
    sem = [n for n in data["semantic"] if not n.startswith("$")]
    colors = ",\n".join(f"        '{n}': 'var(--ez-{n})'" for n in sem)
    prims = []
    for fam, shades in data["color"].items():
        inner = ", ".join(f"'{k}': '{v['$value']}'" for k, v in shades.items() if not k.startswith("$"))
        prims.append(f"        {fam}: {{ {inner} }}")
    space = ", ".join(f"'{k}': 'var(--ez-space-{k})'" for k in data["space"] if not k.startswith("$"))
    radius = ", ".join(f"'{k}': 'var(--ez-radius-{k})'" for k in data["radius"])
    return (
        "// GENERATED by design/tools/build_tokens.py. Optional: the app does not use Tailwind today.\n"
        "// Usage: presets: [require('../../design/tokens/tailwind-preset.js')] and import tokens.css.\n"
        "module.exports = {\n  darkMode: ['variant', [\"@media (prefers-color-scheme: dark) { &:not([data-theme='light'] *) }\", "
        "\"&:is([data-theme='dark'] *)\"]],\n  theme: {\n    extend: {\n      colors: {\n"
        + colors + ",\n" + ",\n".join(prims) + "\n      },\n"
        + f"      spacing: {{ {space} }},\n      borderRadius: {{ {radius} }},\n"
        + "      fontFamily: {\n"
        + ",\n".join(f"        '{k}': 'var(--ez-font-{k})'" for k in data["font"]["family"])
        + "\n      },\n      transitionTimingFunction: { standard: 'var(--ez-ease-standard)', chisel: 'var(--ez-ease-chisel)' },\n"
        "    },\n  },\n};\n"
    )


def contrast_md(data: dict) -> str:
    rows = contrast_rows(data)
    out = [
        "# Contrast results",
        "",
        "Generated by `design/tools/build_tokens.py` from `tokens.json` (WCAG 2.2 relative luminance).",
        "Thresholds: 4.5:1 for normal text (SC 1.4.3 AA), 3:1 for focus rings, borders and UI parts (SC 1.4.11).",
        "",
        f"**{sum(r[-1] for r in rows)} of {len(rows)} pairs pass.** "
        f"Lowest text pair: {min(r[5] for r in rows if r[6] >= 4.5):.2f}:1.",
        "",
        "| Mode | Foreground | Background | FG | BG | Ratio | Needs | AA | AAA (7:1) |",
        "| --- | --- | --- | --- | --- | ---: | ---: | :---: | :---: |",
    ]
    for mode, fg, bg, fv, bv, r, need, ok in rows:
        aaa = "yes" if r >= 7 else ("n/a" if need < 4.5 else "no")
        out.append(f"| {mode} | `{fg}` | `{bg}` | `{fv}` | `{bv}` | {r:.2f} | {need} | {'pass' if ok else 'FAIL'} | {aaa} |")
    restricted = data["contrast"].get("restricted", {}).get("pairs", [])
    if restricted:
        sem = semantic(data)
        out += [
            "",
            "## Restricted pairs: do not use for text",
            "",
            "**Rule: `text-faint` goes only on `bg`, `surface` or `surface-raised`.** On sunk, leaf and tinted",
            "surfaces, use `text-muted`. These pairs are listed so that misuse is visible in review.",
            "",
            "| Mode | Foreground | Background | Ratio | Use instead |",
            "| --- | --- | --- | ---: | --- |",
        ]
        for fg, bg in restricted:
            for mode in ("light", "dark"):
                r = ratio(sem[fg][mode], sem[bg][mode])
                out.append(f"| {mode} | `{fg}` | `{bg}` | {r:.2f} | `text-muted` |")
    out.append("")
    return "\n".join(out)


def main() -> int:
    data = load()
    outputs = {
        TOK / "tokens.css": css(data),
        TOK / "app-compat.css": app_compat(),
        TOK / "tailwind-preset.js": tailwind(data),
        TOK / "CONTRAST.md": contrast_md(data),
    }
    check = "--check" in sys.argv
    stale = []
    for p, text in outputs.items():
        if check:
            if not p.exists() or p.read_text() != text:
                stale.append(p.name)
        else:
            p.write_text(text)
    fails = [r for r in contrast_rows(data) if not r[-1]]
    for r in fails:
        print(f"FAIL {r[0]}: {r[1]} on {r[2]} = {r[5]:.2f} < {r[6]}")
    if stale:
        print("stale generated files:", ", ".join(stale))
    return 1 if fails or stale else 0


if __name__ == "__main__":
    sys.exit(main())
