"""Hero animation paths: the letter ka through five eras, plus the word எழுத்து, as pure vector outlines.

Writes design/glyphs/hero-evolution.json, which app/web reads directly (EvolutionHero.tsx). Outlines come from
the OFL Noto fonts (Tamil-Brahmi, Grantha for the Pallava stage, Noto Serif Tamil for Chola, Noto Sans Tamil for
today); Vatteluttu is the design system's own centre-line drawing (vatteluttu.json), which has no Unicode.
Shipping outlines means the hero never waits for a web font, so there is no layout shift or font swap.

Run: python design/tools/build_hero.py      (fonts: python design/tools/fetch_fonts.py)
"""
from __future__ import annotations

import json
from pathlib import Path

from brandkit import BRAHMI, GRANTHA, TA_SANS, TA_SERIF
from geom import bounds, transform
from outline import path
from vatteluttu import VATTELUTTU

OUT = Path(__file__).resolve().parents[1] / "glyphs" / "hero-evolution.json"
BOX = 70.0  # glyph ink fits a 70-unit square centred on the 100-unit grid (same optical size as the strip)

# key, level, Tamil name, English name, Tamil period, English period, font, character, axes
STAGES = [
    ("brahmi", "L5", "தமிழ்-பிராமி", "Tamil-Brahmi", "கி.மு. 3 நூ. முதல்", "from c. 3rd c. BCE", BRAHMI, "\U00011013", None),
    ("vatteluttu", "L4", "வட்டெழுத்து", "Vatteluttu", "கி.பி. 6–11 நூ.", "c. 6th–11th c. CE", None, None, None),
    ("pallava", "L3", "பல்லவர் (கிரந்த வடிவம்)", "Pallava (Grantha form)", "கி.பி. 6–9 நூ.", "c. 6th–9th c. CE", GRANTHA, "\U00011315", None),
    ("chola", "L2", "சோழர்", "Chola", "கி.பி. 9–13 நூ.", "c. 9th–13th c. CE", TA_SERIF, "க", {"wght": 600}),
    ("modern", "L1", "இன்று", "Today", "இன்று", "today", TA_SANS, "க", {"wght": 500}),
]
WORD = "எழுத்து"


def fit(d: str, box: float = BOX, cx: float = 50, cy: float = 50) -> str:
    x0, y0, x1, y1 = bounds(d)
    s = box / max(x1 - x0, y1 - y0)
    return transform(d, s, s, cx - s * (x0 + x1) / 2, cy - s * (y0 + y1) / 2)


def build() -> dict:
    stages = []
    for key, level, ta, en, pta, pen, font, ch, axes in STAGES:
        if font is None:
            kind, d = "stroke", VATTELUTTU["ka"]["d"]
        else:
            raw, _ = path(ch, font, 100, 0, 0, axes)
            kind, d = "fill", fit(raw)
        stages.append({"key": key, "level": level, "ta": ta, "en": en, "period_ta": pta, "period_en": pen,
                       "kind": kind, "d": d})
    raw, _ = path(WORD, TA_SERIF, 100, 0, 0, {"wght": 600})
    x0, y0, x1, y1 = bounds(raw)
    pad = 6
    word_d = transform(raw, 1, 1, pad - x0, pad - y0)
    w, h = x1 - x0 + 2 * pad, y1 - y0 + 2 * pad
    return {
        "$comment": "Generated by design/tools/build_hero.py. The letter ka at five stages on a 100x100 grid; "
                    "'fill' stages are Noto outlines (SIL OFL), 'stroke' is the Vatteluttu centre line (stroke 8, "
                    "round caps). The Pallava stage uses the Grantha letterform, the closest Unicode relative.",
        "letter": {"iso": "ka", "tamil": "க"},
        "viewBox": "0 0 100 100",
        "stroke": 8,
        "stages": stages,
        "word": {"text": WORD, "viewBox": f"0 0 {w:.0f} {h:.0f}", "d": word_d},
    }


if __name__ == "__main__":
    OUT.write_text(json.dumps(build(), ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parents[2])}")
